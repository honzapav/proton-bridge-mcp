import type { Credentials } from '../types.js';
import { CredentialError } from '../errors.js';
import type { CredentialProvider } from './provider.js';

/**
 * Reads credentials from environment variables.
 *
 * Required env vars:
 *   PROTON_BRIDGE_USERNAME - Proton Bridge account username
 *   PROTON_BRIDGE_PASSWORD - Proton Bridge-specific password
 */
export class EnvCredentialProvider implements CredentialProvider {
  async getCredentials(): Promise<Credentials> {
    const username = process.env.PROTON_BRIDGE_USERNAME;
    const password = process.env.PROTON_BRIDGE_PASSWORD;

    if (!username) {
      throw new CredentialError(
        'PROTON_BRIDGE_USERNAME environment variable is not set.',
        [
          'Set PROTON_BRIDGE_USERNAME to your Proton Mail address.',
          'Set PROTON_BRIDGE_PASSWORD to the bridge-specific password shown in the Proton Bridge app.',
        ],
      );
    }

    if (!password) {
      throw new CredentialError(
        'PROTON_BRIDGE_PASSWORD environment variable is not set.',
        [
          'Set PROTON_BRIDGE_PASSWORD to the bridge-specific password shown in the Proton Bridge app.',
          'Do not use your Proton account password - use the password generated by the Bridge app.',
        ],
      );
    }

    return { username, password };
  }
}
